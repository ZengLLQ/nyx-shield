use curve25519_dalek::constants::RISTRETTO_BASEPOINT_POINT;
use curve25519_dalek::ristretto::RistrettoPoint;
use curve25519_dalek::scalar::Scalar;
use rand_core::{CryptoRng, RngCore};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha512};

/// Receiver dual-key stealth meta-address consisting of public view key and public spend key.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct StealthMetaAddress {
    /// Public view key A = a * G
    pub view_pubkey: RistrettoPoint,
    /// Public spend key B = b * G
    pub spend_pubkey: RistrettoPoint,
}

/// Receiver full keypair holding private keys (a, b) and public meta-address.
#[derive(Clone, Debug)]
pub struct StealthKeypair {
    pub view_secret: Scalar,
    pub spend_secret: Scalar,
    pub meta_address: StealthMetaAddress,
}

impl StealthKeypair {
    /// Generates a new stealth keypair from a secure random number generator.
    pub fn generate<R: RngCore + CryptoRng>(rng: &mut R) -> Self {
        let view_secret = Scalar::random(rng);
        let spend_secret = Scalar::random(rng);
        let g = RISTRETTO_BASEPOINT_POINT;

        let meta_address = StealthMetaAddress {
            view_pubkey: g * view_secret,
            spend_pubkey: g * spend_secret,
        };

        Self {
            view_secret,
            spend_secret,
            meta_address,
        }
    }
}

/// One-time destination address and ephemeral public key generated by a sender.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct OneTimeStealthAddress {
    /// Ephemeral public key R = r * G
    pub ephemeral_pubkey: RistrettoPoint,
    /// Destination stealth address P = B + Hash(r * A) * G
    pub stealth_pubkey: RistrettoPoint,
}

impl OneTimeStealthAddress {
    /// Generates a one-time stealth destination address for a receiver's meta-address.
    pub fn create<R: RngCore + CryptoRng>(
        recipient: &StealthMetaAddress,
        rng: &mut R,
    ) -> Self {
        let r = Scalar::random(rng);
        let g = RISTRETTO_BASEPOINT_POINT;
        let ephemeral_pubkey = g * r;

        // Shared secret S = r * A_view
        let shared_point = recipient.view_pubkey * r;
        let c = hash_shared_secret(&shared_point);

        // One-time stealth address P = B_spend + c * G
        let stealth_pubkey = recipient.spend_pubkey + g * c;

        Self {
            ephemeral_pubkey,
            stealth_pubkey,
        }
    }

    /// Tests if this one-time address belongs to the receiver, and if so, recovers the spending key x.
    pub fn scan_and_derive_spending_key(
        &self,
        receiver: &StealthKeypair,
    ) -> Option<Scalar> {
        let g = RISTRETTO_BASEPOINT_POINT;
        // Shared secret S' = a_view * R
        let shared_point = self.ephemeral_pubkey * receiver.view_secret;
        let c = hash_shared_secret(&shared_point);

        // Check if P == B_spend + c * G
        let expected_p = receiver.meta_address.spend_pubkey + g * c;
        if expected_p == self.stealth_pubkey {
            // Private spending key: x = b_spend + c
            Some(receiver.spend_secret + c)
        } else {
            None
        }
    }
}

/// Hashes an ECDH shared curve point into a field scalar.
fn hash_shared_secret(point: &RistrettoPoint) -> Scalar {
    let mut hasher = Sha512::new();
    hasher.update(b"NyxShield.StealthSharedSecret:");
    hasher.update(point.compress().as_bytes());
    let hash = hasher.finalize();

    let mut wide_bytes = [0u8; 64];
    wide_bytes.copy_from_slice(&hash);
    Scalar::from_bytes_mod_order_wide(&wide_bytes)
}
